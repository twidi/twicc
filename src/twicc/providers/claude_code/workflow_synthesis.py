"""Synthesize a workflow run's "running view" (STATE 1) while it is still live.

A running workflow only records its phase→agent mapping at completion (in the
final ``wf_*.json``). To show a run *in progress* we reconstruct that mapping
from three sources, none of which is the agents' raw JSONL (the watcher already
owns their ingestion):

  - the run's live ``journal.jsonl`` — which agents started / returned, and the
    schema ``result`` each returned;
  - each agent's prompt — its workflow-subagent's first user message, already in
    the DB under the composite id ``<run_id>:<agent_id>``;
  - ``templates`` — ``[{phase, segments}]`` generated by a viewing front from the
    launch script (stored in ``Workflow.synthesis``).

:func:`detect_phase` matches a prompt against the templates; :func:`build_state1`
assembles the **common view format** (mirrors the ``wf_*.json`` envelope, marked
``synthetic``) so the front renders a running run and a finished one identically.

Pure Python, DB-driven, no eval — the template *generation* (eval of the script)
happens in the browser; only this string-matching half runs on the back.
"""
from __future__ import annotations

import logging
import re

import orjson

from twicc.core.enums import Provider
from twicc.provider_homes import claude_projects_dir


logger = logging.getLogger(__name__)

_WS_RE = re.compile(r"\s+")


def _norm(text: str) -> str:
    """Collapse runs of whitespace to single spaces and trim (matches the
    template generator's ``norm`` so segments compare on equal footing)."""
    return _WS_RE.sub(" ", text).strip()


def detect_phase(prompt: str, templates: list[dict]) -> str | None:
    """Best-matching phase title for ``prompt`` among ``templates``, or ``None``.

    Faithful port of the playground's Script B: a template is a candidate when at
    least half its (already whitespace-normalized) static segments appear as
    substrings of the normalized prompt; among candidates the one matching the
    most total text wins. Different phases carry distinct instruction blocks, so
    cross-phase confusion does not happen. The "half" tolerance absorbs a baked
    enum the live agent lacks, or a truncated first message.
    """
    normalized = _norm(prompt)
    best_phase: str | None = None
    best_score = -1
    for tpl in templates:
        segments = tpl.get("segments") or []
        if not segments:
            continue
        present = [seg for seg in segments if seg in normalized]
        if len(present) >= max(1, len(segments) // 2):
            score = sum(len(seg) for seg in present)
            if score > best_score:
                best_score = score
                best_phase = tpl.get("phase")
    return best_phase


def _journal_path(project_id: str, session_id: str, run_id: str):
    """Path of a run's live resume journal (read-only; the watcher owns writes)."""
    return (
        claude_projects_dir()
        / project_id
        / session_id
        / "subagents"
        / "workflows"
        / run_id
        / "journal.jsonl"
    )


def _wf_json_path(project_id: str, session_id: str, run_id: str):
    """Path of a run's completion envelope (``wf_<runId>.json``)."""
    return (
        claude_projects_dir() / project_id / session_id / "workflows" / f"{run_id}.json"
    )


def _mtime(path) -> float | None:
    """File mtime in seconds, or ``None`` if it doesn't exist / can't be stat'd."""
    try:
        return path.stat().st_mtime
    except OSError:
        return None


def _script_start_time_ms(project_id: str, session_id: str, run_id: str) -> int | None:
    """Best-effort launch time of a live run: the mtime of its launch script.

    The engine writes ``workflows/scripts/<name>-<run_id>.js`` once, at launch, so
    its mtime is a stable proxy for "when the run started" — the only such signal
    available while a run is in flight (the journal carries no timestamps, and
    OSes don't reliably expose a file's birth time). STATE 2 never uses this: a
    finished run reads ``startTime``/``durationMs`` straight from its wf_*.json.
    """
    scripts_dir = (
        claude_projects_dir() / project_id / session_id / "workflows" / "scripts"
    )
    try:
        matches = sorted(scripts_dir.glob(f"*-{run_id}.js"))
    except OSError:
        return None
    for path in matches:
        try:
            return int(path.stat().st_mtime * 1000)
        except OSError:
            continue
    return None


def _read_journal(project_id: str, session_id: str, run_id: str) -> list[dict]:
    """Parse the run journal into ``{type, key, agentId, result?}`` events.

    Missing file → ``[]`` (the run may not have spawned an agent yet). A partial
    last line caught mid-write fails to parse and is skipped, like the wf_*.json
    upsert path.
    """
    path = _journal_path(project_id, session_id, run_id)
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return []
    events: list[dict] = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            events.append(orjson.loads(line))
        except orjson.JSONDecodeError:
            continue
    return events


def _agent_sessions(run_id: str) -> dict[str, dict]:
    """Per-agent Session metadata for a run, keyed by agent_id.

    Workflow agents are Sessions keyed ``<run_id>:<agent_id>`` (already synced by
    the watcher). We surface the few fields the real wf_*.json carries that the
    journal lacks — model + timing — so the synthetic STATE 1 envelope mirrors it.
    """
    from twicc.core.models import Session

    prefix = f"{run_id}:"
    rows = Session.objects.filter(id__startswith=prefix).values(
        "id", "model", "last_started_at", "last_updated_at", "total_cost"
    )
    return {r["id"][len(prefix):]: r for r in rows}


def _to_ms(dt) -> int | None:
    """Aware datetime → epoch milliseconds (matches the engine's startedAt/…)."""
    return int(dt.timestamp() * 1000) if dt is not None else None


def _launch_args(session_id: str, run_id: str):
    """The ``args`` passed to the Workflow tool that launched ``run_id``, or None.

    The final wf_*.json carries ``args``, but a still-running STATE 1 run has no
    such file yet — the args only live in the launching tool_use's input. Map
    run_id → tool_use_id via the tool_result's ``toolUseResult.runId`` (like
    :func:`views._derive_workflow_links`), then read that Workflow tool_use's
    ``input.args``. Read-only, from synced SessionItems (survives JSONL removal).
    Called once per run then cached in the envelope — never re-scanned each tick.
    """
    from twicc.core.models import SessionItem

    base = SessionItem.objects.filter(session_id=session_id).only("content")
    # 1) run_id → launching tool_use_id (from its tool_result).
    tool_use_id = None
    for it in base.filter(content__contains=run_id).iterator(chunk_size=20):
        try:
            parsed = orjson.loads(it.content)
        except orjson.JSONDecodeError:
            continue
        tur = parsed.get("toolUseResult")
        if not isinstance(tur, dict) or tur.get("runId") != run_id:
            continue
        content = (parsed.get("message") or {}).get("content")
        if isinstance(content, list):
            tool_use_id = next(
                (b.get("tool_use_id") for b in content
                 if isinstance(b, dict) and b.get("type") == "tool_result"),
                None,
            )
        if tool_use_id:
            break
    if not tool_use_id:
        return None
    # 2) tool_use_id → the Workflow tool_use's input.args.
    for it in base.filter(content__contains=tool_use_id).iterator(chunk_size=20):
        try:
            parsed = orjson.loads(it.content)
        except orjson.JSONDecodeError:
            continue
        content = (parsed.get("message") or {}).get("content")
        if not isinstance(content, list):
            continue
        for b in content:
            if (isinstance(b, dict) and b.get("type") == "tool_use"
                    and b.get("id") == tool_use_id and b.get("name") == "Workflow"):
                return (b.get("input") or {}).get("args")
    return None


def build_state1(
    run_id: str,
    project_id: str,
    session_id: str,
    synthesis: dict,
    script: str | None,
    prior_args=None,
) -> dict:
    """Assemble the STATE 1 (synthesized) view envelope for a live run.

    ``synthesis`` is ``{meta, templates}`` (front-supplied). Agents are discovered
    from the **union of the agent Sessions and the journal**: each spawned agent
    is a Session keyed ``<run_id>:<agent_id>`` that syncs in real time (the instant
    its first message lands), whereas the journal is written by the engine in
    bursts — so discovering agents from the Sessions surfaces each one the moment
    its prompt is in the DB (in its detected phase), instead of waiting for the
    next journal burst. The journal supplies only what the Sessions can't: an
    agent's ``completed`` state and its structured ``result``. Agents are ordered
    by their Session ``last_started_at`` (the true start order). An agent whose
    first user message hasn't synced yet is skipped (no prompt → no phase) and
    reappears on its own file's next sync (the watcher rebuilds then).

    ``prior_args`` is the args already resolved on an earlier rebuild (carried in
    the prior envelope) — passed back so the launching tool_use is scanned at most
    once per run, not every tick.
    """
    meta = synthesis.get("meta") or {}
    templates = synthesis.get("templates") or []
    phases = meta.get("phases") or []
    # phaseIndex is 1-based, mirroring the engine's wf_*.json (phases[0] → index 1):
    # the front matches agents to phases by title, but the synthetic envelope stays
    # a faithful mirror of the real one so both states share one shape.
    phase_index = {p.get("title"): i + 1 for i, p in enumerate(phases) if isinstance(p, dict)}

    # Journal state per agent: the only source of an agent's ``completed`` state
    # and its structured ``result``. NOT used to *discover* agents — the journal
    # lags in bursts, which made agents appear all at once in a block.
    journal_state: dict[str, dict] = {}
    for event in _read_journal(project_id, session_id, run_id):
        agent_id = event.get("agentId")
        if not agent_id:
            continue
        info = journal_state.setdefault(agent_id, {"state": "running", "result": None})
        if event.get("type") == "result":
            info["state"] = "completed"
            info["result"] = event.get("result")

    helpers = _get_helpers()
    # Real-time discovery source: every agent the engine has spawned has a synced
    # Session (keyed ``<run_id>:<agent_id>``), written as it runs. Union with the
    # journal in case it ever names an agent whose Session hasn't synced (skipped
    # below for lack of a prompt, but its journal state is then ready).
    agent_meta = _agent_sessions(run_id)
    candidate_ids = set(journal_state) | set(agent_meta)
    progress: list[dict] = [
        {"type": "workflow_phase", "index": i + 1, "title": p.get("title")}
        for i, p in enumerate(phases)
        if isinstance(p, dict)
    ]

    def _start_order(agent_id: str):
        # Order by the Session's real start time; the journal's bursty order would
        # reshuffle as it catches up. A journal-only agent (no Session) sorts last,
        # by id, deterministically.
        row = agent_meta.get(agent_id)
        started = _to_ms(row.get("last_started_at")) if row else None
        return (started is None, started or 0, agent_id)

    surfaced_index = 0
    for agent_id in sorted(candidate_ids, key=_start_order):
        # Skip an agent until its first user message has synced: without it we
        # can't detect its phase, and surfacing it phase-less would drop it under
        # "Unassigned" only to move it seconds later — jarring at the eye. It
        # reappears on its own file's next sync (the watcher rebuilds then).
        prompt = helpers.get_first_user_message(f"{run_id}:{agent_id}")
        if prompt is None:
            continue
        surfaced_index += 1
        # A Session-only agent the journal hasn't reported yet is ``running``.
        info = journal_state.get(agent_id) or {"state": "running", "result": None}
        # ``index`` is the 1-based ordinal among surfaced agents, in start order.
        # model/startedAt/lastProgressAt/durationMs come from the agent's synced
        # Session — the journal carries no timestamps.
        entry: dict = {"type": "workflow_agent", "index": surfaced_index, "agentId": agent_id, "state": info["state"]}
        meta_row = agent_meta.get(agent_id)
        if meta_row:
            if meta_row.get("model"):
                entry["model"] = meta_row["model"]
            started_ms = _to_ms(meta_row.get("last_started_at"))
            progress_ms = _to_ms(meta_row.get("last_updated_at"))
            if started_ms is not None:
                entry["startedAt"] = started_ms
            if progress_ms is not None:
                entry["lastProgressAt"] = progress_ms
            if started_ms is not None and progress_ms is not None:
                entry["durationMs"] = max(0, progress_ms - started_ms)
            if meta_row.get("total_cost") is not None:
                entry["cost"] = float(meta_row["total_cost"])
        # Full prompt, not a preview: we have it (the agent's first user message)
        # and storing it whole is durable past Claude deleting the run's files.
        entry["promptPreview"] = prompt
        phase_title = detect_phase(prompt, templates)
        if phase_title is not None:
            entry["phaseTitle"] = phase_title
            if phase_title in phase_index:
                entry["phaseIndex"] = phase_index[phase_title]
        if info["result"] is not None:
            # Full result as its structured value (not stringified/truncated), so
            # the front renders a clean JsonHumanView.
            entry["resultPreview"] = info["result"]
        progress.append(entry)

    # Args live only in the launching tool_use until the final wf_*.json — recover
    # them once (reusing a value already found on a prior rebuild). STATE 2 carries
    # its own args verbatim.
    args = prior_args if prior_args is not None else _launch_args(session_id, run_id)

    envelope = {
        "synthetic": True,
        "status": "pending",
        "runId": run_id,
        "workflowName": meta.get("name"),
        "summary": meta.get("description"),
        "args": args,
        # Launch time (script mtime) so the front can show a start time + a live
        # duration for a run still in flight. STATE 2 overwrites this with the
        # wf_*.json's own startTime/durationMs.
        "startTime": _script_start_time_ms(project_id, session_id, run_id),
        "phases": phases,
        "script": script,
        # Surfaced agents only (prompt-less ones are skipped above) — so the header
        # count matches what's shown; a still-syncing agent isn't counted yet.
        "agentCount": sum(1 for e in progress if e.get("type") == "workflow_agent"),
        "workflowProgress": progress,
    }
    # The front couldn't build templates (script wouldn't execute), so phase
    # detection ran with none → every agent is Unassigned. Flag it so the front
    # shows a "phases undetectable" callout (vs the normal odd-agent Unassigned).
    if synthesis.get("detectionUnavailable"):
        envelope["detectionUnavailable"] = True
    # Derive each phase's state from its agents (same field STATE 2 gets, below).
    return stamp_phase_states(envelope)


def _run_resumed(project_id: str, session_id: str, run_id: str) -> bool:
    """True if a completed run (STATE 2) has **resumed** — its live journal is
    newer than its ``wf_*.json`` (or the envelope file is gone while the journal
    lives). Claude reuses the ``runId`` and the **same** ``journal.jsonl`` on
    resume, so a journal that grew *after* the completion envelope means the run
    is producing agents the stored envelope doesn't know → flip back to a live
    STATE 1 until the final ``wf_*.json`` is rewritten (which makes the envelope
    newer again). Compares the two files' mtimes (one filesystem, one clock) — a
    deleted envelope counts as "resumed" too (a moving journal wins)."""
    journal_mtime = _mtime(_journal_path(project_id, session_id, run_id))
    if journal_mtime is None:
        return False  # no journal → nothing live to show
    wf_mtime = _mtime(_wf_json_path(project_id, session_id, run_id))
    return wf_mtime is None or journal_mtime > wf_mtime


def rebuild_state1(run_id: str) -> dict | None:
    """Rebuild a run's STATE 1 ``raw_json`` from its stored synthesis + live
    journal, persist it, and return the new envelope dict.

    Returns ``None`` (no write) when the run is not in a synthesizable state: no
    row, or no ``synthesis`` (no front ever generated templates). A run whose real
    envelope already landed (STATE 2) is normally left alone — **except** when it
    has **resumed** (:func:`_run_resumed`): the same ``runId`` restarted, its
    journal grew past the envelope, so we re-synthesize a live STATE 1 from the
    retained templates until the final ``wf_*.json`` is rewritten. Sync; wrap in
    ``sync_to_async`` at the call site.
    """
    from twicc.core.models import Workflow

    try:
        workflow = Workflow.objects.select_related("session").get(run_id=run_id)
    except Workflow.DoesNotExist:
        return None
    if not workflow.synthesis:
        return None
    try:
        prior = orjson.loads(workflow.raw_json)
    except orjson.JSONDecodeError:
        prior = {}
    if not prior.get("synthetic") and not _run_resumed(
        workflow.session.project_id, workflow.session_id, run_id
    ):
        return None  # STATE 2 and not resumed — never regress a completed run

    envelope = build_state1(
        run_id,
        workflow.session.project_id,
        workflow.session_id,
        workflow.synthesis,
        prior.get("script"),
        prior.get("args"),
    )
    workflow.cost, workflow.phases_cost = Workflow.compute_costs(run_id, envelope)
    workflow.raw_json = orjson.dumps(envelope).decode()
    workflow.save(update_fields=["raw_json", "cost", "phases_cost", "updated_at"])
    return envelope


def agent_first_message(run_id: str, agent_id: str) -> str | None:
    """The workflow agent's first user message (its prompt), or ``None`` if its
    Session/items aren't synced to the DB yet.

    Same lookup :func:`build_state1` uses to detect a phase, exposed for the
    watcher's agent-sync rebuild: an agent is discovered the moment its Session
    syncs, but :func:`build_state1` can only surface it once its prompt is in the
    DB; the watcher pre-checks this on an agent-file sync so it rebuilds only when
    the prompt is actually there. Sync; wrap in ``sync_to_async`` at the call site.
    """
    return _get_helpers().get_first_user_message(f"{run_id}:{agent_id}")


# Tokens we've actually observed. Success: a run/agent that finished OK. Pending:
# not started. Everything else on a *terminal* envelope is a non-success we don't
# try to name — the engine's status vocabulary is undocumented, and the only
# non-success run status we've seen is "killed" (a clean Ctrl-C, agents frozen at
# "progress"). Guessing "failed"/"error"/"cancelled" bought nothing (it missed the
# real "killed"/"progress") so we don't: we surface a single ``interrupted`` kind
# and relay the raw status/state verbatim as the label.
_SUCCESS_STATES = {"completed", "success", "done"}
_PENDING_STATES = {"queued", "pending"}


def _run_status_kind(envelope: dict) -> str:
    """Normalized run status — ``running`` / ``completed`` / ``interrupted``.

    A finished envelope is ``completed`` only for a known success status.
    ``synthetic`` (our STATE 1 marker) is otherwise ``running`` — it's our own
    flag, never a guess — *unless* it was explicitly stamped ``interrupted``
    (an orphaned run: the session restarted without its ``wf_*.json`` ever
    landing — see :func:`apply_orphan_status`). Any other terminal status
    (``killed``, or one we've never seen) is ``interrupted``, derived by
    exclusion so an unknown status can never fall back to a forever-spinning
    ``running``. The raw ``status`` stays in the envelope for an honest label."""
    status = str(envelope.get("status") or "").lower()
    if status in _SUCCESS_STATES:
        return "completed"
    if envelope.get("synthetic") and status != "interrupted":
        return "running"
    return "interrupted"


def _agent_status_kind(state, run_terminal: bool) -> str:
    """Normalized agent status — ``completed`` / ``running`` / ``interrupted`` /
    ``pending``.

    Finished-OK tokens are ``done`` (STATE 2) / ``completed`` (our STATE 1); the
    in-flight token is ``progress`` (STATE 2) / ``running`` (STATE 1). An agent
    still in flight when the run ended terminally — a killed run freezes its
    agents at ``progress`` — is ``interrupted``, neither ``completed`` (it never
    finished) nor a forever-spinning ``running``. By exclusion, so an unknown
    token is handled the same honest way."""
    s = str(state or "").lower()
    if s in _SUCCESS_STATES:
        return "completed"
    if s in _PENDING_STATES:
        return "pending"
    return "interrupted" if run_terminal else "running"


def _phase_state(agent_kinds: list[str]) -> str:
    """A phase's status from its agents' normalized kinds: ``pending`` (none
    started), ``interrupted`` (≥1 agent interrupted), ``running`` (≥1 started
    agent unfinished), or ``completed`` (every started agent finished OK)."""
    started = [k for k in agent_kinds if k != "pending"]
    if not started:
        return "pending"
    if any(k == "interrupted" for k in started):
        return "interrupted"
    if any(k == "running" for k in started):
        return "running"
    return "completed"


def stamp_phase_states(envelope: dict) -> dict:
    """Normalize every derived state field the UI + CLI read, on both STATE 1
    (synthetic) and STATE 2 (the real envelope, shipped without any of them), so
    neither side re-guesses the engine's undocumented status vocabulary. Mutates
    and returns ``envelope``. Sets:

      - run-level ``statusKind`` — ``running`` / ``completed`` / ``interrupted``;
      - per-agent ``statusKind`` on each ``workflow_agent`` — ``completed`` /
        ``running`` / ``interrupted`` / ``pending``;
      - per-phase ``state`` on each ``workflow_phase`` — ``pending`` / ``running``
        / ``completed`` / ``interrupted``, from the agents matched by ``phaseIndex``;
      - a run-level ``phaseCompletion`` summary ``{total, completed, allCompleted}``.

    The raw ``status`` / agent ``state`` are left untouched (the label relays them
    verbatim). ``phaseCompletion`` surfaces the "marked completed but not every
    phase ran" case (stopped early, e.g. a budget cap: ``status`` stays
    ``completed`` yet ``allCompleted`` is ``False``); ``statusKind:"interrupted"``
    surfaces a run cut short (e.g. killed). Both derive from the agents actually
    observed — never the script-built ``result``/``logs``.

    Agents with no ``phaseIndex`` (e.g. a live agent whose phase isn't detected
    yet) belong to no phase here, exactly like the front's per-phase grouping; the
    front still buckets them under "Unassigned" on its own."""
    envelope["statusKind"] = _run_status_kind(envelope)
    run_terminal = envelope["statusKind"] != "running"

    progress = envelope.get("workflowProgress")
    if not isinstance(progress, list):
        return envelope

    by_phase: dict[object, list[str]] = {}
    for entry in progress:
        if isinstance(entry, dict) and entry.get("type") == "workflow_agent":
            kind = _agent_status_kind(entry.get("state"), run_terminal)
            entry["statusKind"] = kind
            if entry.get("phaseIndex") is not None:
                by_phase.setdefault(entry["phaseIndex"], []).append(kind)

    total = 0
    completed = 0
    for entry in progress:
        if isinstance(entry, dict) and entry.get("type") == "workflow_phase":
            state = _phase_state(by_phase.get(entry.get("index"), []))
            entry["state"] = state
            total += 1
            if state == "completed":
                completed += 1
    envelope["phaseCompletion"] = {
        "total": total,
        "completed": completed,
        # No phases declared → nothing can be "incomplete" (allCompleted stays True).
        "allCompleted": completed == total if total else True,
    }
    return envelope


def apply_orphan_status(envelope: dict, workflow_updated_at, session_cutoff) -> dict:
    """Mark an orphaned run ``interrupted`` at **read time** (never persisted).
    Mutates and returns ``envelope``.

    A run whose envelope is still ``synthetic`` (STATE 0/1 — no real ``wf_*.json``
    ever landed) yet was last touched **before** its session's most recent
    lifecycle boundary (``Session.cutoff`` = max of ``last_started_at`` /
    ``last_stopped_at``) belonged to a run that has since **restarted or stopped**
    without writing its envelope — i.e. it died. We can't write this into
    ``raw_json`` (no file event fires for a crash that writes *nothing*), so we
    derive it whenever the envelope is served (REST + CLI both call this).

    Using ``cutoff`` (not just ``last_started_at``) also catches a run whose
    session **stopped and was never resumed**. Residual gap: ``last_stopped_at``
    is set only for TwiCC-driven sessions ("our processes only"), so a
    hard-killed-and-never-resumed run, or an external/hybrid session, can still
    slip through (would need the journal mtime to catch).

    ``synthetic`` stays truthful (it *is* a reconstructed view); we only stamp
    ``status="interrupted"`` and re-run :func:`stamp_phase_states`, which flips
    the run, its agents and phases to ``interrupted`` (``_run_status_kind`` honors
    the explicit ``interrupted`` status even while ``synthetic``).

    Timestamps are aware datetimes on the same host (``updated_at`` is
    ``auto_now``; ``cutoff`` derives from the session lifecycle) — comparable; the
    gap we test (a resume/stop, minutes/hours later) dwarfs any sub-second drift.
    """
    if (
        isinstance(envelope, dict)
        and envelope.get("synthetic")
        and session_cutoff is not None
        and workflow_updated_at is not None
        and workflow_updated_at < session_cutoff
    ):
        envelope["status"] = "interrupted"
        stamp_phase_states(envelope)
    return envelope


def enrich_previews(envelope: dict, project_id: str, session_id: str, run_id: str) -> dict:
    """Enrich each agent: full promptPreview/resultPreview (vs the engine's
    truncated ones) + its per-agent cost. Mutates and returns ``envelope``
    (STATE 2 ingestion).

    The engine truncates these for its own CLI display; we keep the full data,
    which is **durable past Claude's eventual deletion of the run's files** (the
    reason we mirror the envelope at all). Sources:
      - prompt ← the agent session's first user message (synced, persists in DB);
      - result ← the run journal's ``result`` event for the agent (present until
        the subagent files are sublimated).
    Each falls back to the envelope's own value when its source is unavailable.
    Sync; the caller wraps it (live watcher path / boot db-writer path).
    """
    progress = envelope.get("workflowProgress")
    if not isinstance(progress, list):
        return envelope
    agents = [e for e in progress if isinstance(e, dict) and e.get("type") == "workflow_agent"]
    if not agents:
        return envelope
    results = {
        event["agentId"]: event.get("result")
        for event in _read_journal(project_id, session_id, run_id)
        if event.get("type") == "result" and event.get("agentId")
    }
    sessions = _agent_sessions(run_id)
    helpers = _get_helpers()
    for entry in agents:
        agent_id = entry.get("agentId")
        if not agent_id:
            continue
        prompt = helpers.get_first_user_message(f"{run_id}:{agent_id}")
        if prompt is not None:
            entry["promptPreview"] = prompt
        if results.get(agent_id) is not None:
            entry["resultPreview"] = results[agent_id]
        # The engine's STATE 2 agents carry durationMs but no cost — stamp it from
        # the agent session's total_cost (matches the per-agent cost build_state1 adds).
        cost = sessions.get(agent_id, {}).get("total_cost")
        if cost is not None:
            entry["cost"] = float(cost)
    return envelope


def _get_helpers():
    # Lazy: avoid importing the provider-helpers graph at module load (the
    # watcher and views import this module on a hot path).
    from twicc.providers.helpers import get_provider_helpers

    return get_provider_helpers(Provider.CLAUDE_CODE)
